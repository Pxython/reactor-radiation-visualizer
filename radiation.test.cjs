const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let pixels=0, clears=0;
const drawing={clearRect(){pixels=0;clears++;},fillRect(){pixels++;}};
const control=()=>({checked:true,addEventListener(type,fn){this.change=fn;}});
const controls={snow:control(),distortion:control(),geiger:control()};
const doc={hidden:false,addEventListener(type,fn){this.visibility=fn;}};
const sandbox={window:{innerWidth:1200,innerHeight:800,addEventListener(){},setInterval(){}},document:doc,Float32Array,Math};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'radiation.js'),'utf8')+';this.Effects=RadiationEffects;',sandbox);
const fx=new sandbox.Effects({getContext:()=>drawing},controls);
const param=()=>({value:0,setTargetAtTime(v){this.value=v;}});
const node=()=>({gain:param(),connect(){},disconnect(){this.disconnected=true;},start(t){this.when=t;},stop(){this.stopped=true;}});
const ctx={currentTime:1,sampleRate:48000,state:'running',destination:{},createGain:node,createWaveShaper:node,createBuffer:(c,n)=>({getChannelData:()=>new Float32Array(n)}),createBufferSource:node};
fx.connect(ctx,node(),node());
const update=(h,t)=>fx.update([{h}],1,true,t);
update(.07,40);assert.equal(fx.level,0);assert.equal(pixels,0);assert.equal(fx.wet.gain.value,0);
update(1.27,80);const lowPixels=pixels, lowWet=fx.wet.gain.value, lowDrive=fx.drive.gain.value;
update(4.87,120);assert.ok(pixels>lowPixels);assert.ok(fx.wet.gain.value>lowWet);assert.ok(fx.drive.gain.value>lowDrive);assert.equal(fx.level,1);
controls.snow.checked=false;controls.snow.change();assert.equal(pixels,0);assert.ok(fx.wet.gain.value>0);
controls.distortion.checked=false;controls.distortion.change();assert.equal(fx.wet.gain.value,0);assert.equal(fx.dry.gain.value,1);
fx.scheduleClicks();assert.ok(fx.clicks.size>0);const pending=[...fx.clicks];controls.geiger.checked=false;controls.geiger.change();assert.equal(fx.clicks.size,0);assert.ok(pending.every(n=>n.stopped&&n.disconnected));assert.equal(fx.geiger.gain.value,0);
controls.geiger.checked=true;fx.setVolume(0);assert.equal(fx.geiger.gain.value,0);fx.setVolume(.5);assert.ok(fx.geiger.gain.value>0);
fx.scheduleClicks();fx.stop();assert.equal(fx.clicks.size,0);assert.equal(fx.geiger.gain.value,0);assert.equal(fx.wet.gain.value,0);
update(4.87,160);doc.hidden=true;doc.visibility();fx.scheduleClicks();assert.equal(fx.clicks.size,0);assert.equal(pixels,0);
doc.hidden=false;controls.snow.checked=true;update(100,200);assert.equal(fx.level,1);assert.ok(pixels<=14000);
console.log('PASS: amplitude scaling, effect independence, dry bypass, click cleanup, mute, stop, hidden tab and bounds');
